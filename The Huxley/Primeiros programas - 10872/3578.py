numero_1 = int(input("Digite o primeiro valor numérico: "));
numero_2 = int(input("Digite o segundo valor numérico: "));

soma = numero_1 + numero_2;
subtracao = numero_1 - numero_2;
multiplicacao = numero_1 * numero_2;
divisao = numero_1 / numero_2;

print(soma, subtracao, multiplicacao, divisao, sep="\n");